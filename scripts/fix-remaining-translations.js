function patchLocale(locale) {
  const filePath = path.join(translationsDir, `${locale}.json`);
  const json = JSON.parse(fs.readFileSync(filePath, 'utf8'));

  if (hikeTitles[locale] && json.tasks?.baseTasks) {
    json.tasks.baseTasks.hike = hikeTitles[locale];
  }

  if (singASongTitles[locale] && json.tasks?.baseTasks) {
    json.tasks.baseTasks.singASong = singASongTitles[locale];
  }

  if (subscriptionBlocks[locale]) {
    json.subscription = subscriptionBlocks[locale];
  }

  if (errorAlreadyExists[locale] && json.onboarding?.sign_up) {
    json.onboarding.sign_up.error_already_exists = errorAlreadyExists[locale];
  }

  fs.writeFileSync(filePath, `${JSON.stringify(json, null, 2)}\n`, 'utf8');
}

for (const locale of Object.keys(hikeTitles)) {
  patchLocale(locale);
}

for (const locale of Object.keys(subscriptionBlocks)) {
  patchLocale(locale);
}

